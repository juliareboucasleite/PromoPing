#!/usr/bin/env node

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.join(__dirname, "..");
const inputPath = path.join(projectRoot, "sql", "PAPv5.sql");
const outputPath = path.join(projectRoot, "sql", "PAPv5.postgres.sql");

function normalizeStatement(sql) {
  return sql
    .replace(/`/g, "")
    .replace(/AUTO_INCREMENT=(\d+)/gi, "AUTO_INCREMENT_START=$1")
    .replace(/\bint\(\d+\)\s+unsigned/gi, "INTEGER")
    .replace(/\bint\(\d+\)/gi, "INTEGER")
    .replace(/\btinyint\(1\)/gi, "INTEGER")
    .replace(/\bdatetime\b/gi, "TIMESTAMP")
    .replace(/\blongtext\b/gi, "TEXT")
    .replace(/\bmediumtext\b/gi, "TEXT")
    .replace(/\benum\((?:[^)(]+|\([^)(]*\))*\)/gi, "VARCHAR(100)")
    .replace(/\bcurrent_timestamp\(\)/gi, "CURRENT_TIMESTAMP")
    .replace(/\s+ON UPDATE CURRENT_TIMESTAMP/gi, "")
    .replace(/\)\s*ENGINE=.*?;/gi, ");")
    .replace(/\s+DEFAULT CHARSET=\w+/gi, "")
    .replace(/\s+CHARSET=\w+/gi, "")
    .replace(/\s+COLLATE=\w+/gi, "")
    .replace(/\bAUTO_INCREMENT\b/gi, "GENERATED BY DEFAULT AS IDENTITY")
    .replace(/,\s*$/gm, ",");
}

function cleanColumnList(columns) {
  return columns.replace(/\(\d+\)/g, "").trim();
}

function transformCreateTable(statement) {
  let sql = normalizeStatement(statement);
  const inlineIndexes = [];

  sql = sql.replace(/^\s*CREATE TABLE\s+(?:IF NOT EXISTS\s+)?([^(]+)\s*\(/i, (match, tableName) => {
    return `CREATE TABLE IF NOT EXISTS ${tableName.trim()} (`;
  });

  sql = sql.replace(/^\s*(UNIQUE\s+)?KEY\s+([A-Za-z0-9_]+)\s*\(([^)]+)\),?\s*$/gim, (match, isUnique, indexName, columns) => {
    inlineIndexes.push({
      unique: Boolean(isUnique),
      name: indexName,
      columns: cleanColumnList(columns),
    });
    return "";
  });

  sql = sql.replace(/^\s*INDEX\s+([A-Za-z0-9_]+)\s*\(([^)]+)\),?\s*$/gim, (match, indexName, columns) => {
    inlineIndexes.push({
      unique: false,
      name: indexName,
      columns: cleanColumnList(columns),
    });
    return "";
  });

  sql = sql.replace(/,\s*\)/g, "\n)");

  const statements = [sql.trim()];
  const tableMatch = sql.match(/CREATE TABLE IF NOT EXISTS\s+([^\s(]+)/i);
  const tableName = tableMatch?.[1];

  if (tableName) {
    for (const indexDef of inlineIndexes) {
      const prefix = indexDef.unique ? "CREATE UNIQUE INDEX" : "CREATE INDEX";
      statements.push(
        `${prefix} IF NOT EXISTS ${indexDef.name} ON ${tableName} (${indexDef.columns});`
      );
    }
  }

  return statements.join("\n");
}

function transformAlterTable(statement) {
  const compact = normalizeStatement(statement)
    .replace(/\s+/g, " ")
    .replace(/;$/, "")
    .trim();

  const tableMatch = compact.match(/^ALTER TABLE\s+([^\s]+)\s+(.*)$/i);
  if (!tableMatch) return "";

  const tableName = tableMatch[1];
  const actions = tableMatch[2].split(/,\s+(?=ADD|MODIFY)/i);
  const output = [];

  for (const rawAction of actions) {
    const action = rawAction.trim();

    let match = action.match(/^ADD PRIMARY KEY\s*\((.+)\)$/i);
    if (match) {
      output.push(`ALTER TABLE ${tableName} ADD PRIMARY KEY (${cleanColumnList(match[1])});`);
      continue;
    }

    match = action.match(/^ADD UNIQUE KEY\s+([A-Za-z0-9_]+)\s*\((.+)\)$/i);
    if (match) {
      output.push(`CREATE UNIQUE INDEX IF NOT EXISTS ${match[1]} ON ${tableName} (${cleanColumnList(match[2])});`);
      continue;
    }

    match = action.match(/^ADD KEY\s+([A-Za-z0-9_]+)\s*\((.+)\)$/i);
    if (match) {
      output.push(`CREATE INDEX IF NOT EXISTS ${match[1]} ON ${tableName} (${cleanColumnList(match[2])});`);
      continue;
    }

    match = action.match(/^ADD CONSTRAINT\s+([A-Za-z0-9_]+)\s+FOREIGN KEY\s*\((.+?)\)\s+REFERENCES\s+([^\s(]+)\s*\((.+?)\)(.*)$/i);
    if (match) {
      output.push(
        `ALTER TABLE ${tableName} ADD CONSTRAINT ${match[1]} FOREIGN KEY (${cleanColumnList(match[2])}) REFERENCES ${match[3]} (${cleanColumnList(match[4])})${match[5]};`
      );
      continue;
    }

    match = action.match(/^MODIFY\s+([A-Za-z0-9_]+)\s+.+?GENERATED BY DEFAULT AS IDENTITY(?:,\s*AUTO_INCREMENT_START=(\d+))?$/i);
    if (match) {
      const startWith = match[2] ? ` (START WITH ${match[2]})` : "";
      output.push(`ALTER TABLE ${tableName} ALTER COLUMN ${match[1]} ADD GENERATED BY DEFAULT AS IDENTITY${startWith};`);
      continue;
    }
  }

  return output.join("\n");
}

function transformMiscStatement(statement) {
  return normalizeStatement(statement)
    .replace(/^START TRANSACTION;$/i, "BEGIN;")
    .replace(/^SET SQL_MODE.*$/i, "")
    .replace(/^SET time_zone.*$/i, "")
    .replace(/^\/\*![\s\S]*?\*\/;?$/gm, "")
    .trim();
}

function buildStatements(source) {
  const lines = source.split(/\r?\n/);
  const statements = [];
  let buffer = [];
  let inCustomDelimiterBlock = false;

  for (const line of lines) {
    const trimmed = line.trim();

    if (/^DELIMITER\s+;/i.test(trimmed)) {
      inCustomDelimiterBlock = false;
      continue;
    }

    if (/^DELIMITER\s+/i.test(trimmed)) {
      inCustomDelimiterBlock = true;
      continue;
    }

    if (inCustomDelimiterBlock) {
      continue;
    }

    if (/^--/.test(trimmed) || trimmed === "") {
      continue;
    }

    buffer.push(line);
    if (trimmed.endsWith(";")) {
      statements.push(buffer.join("\n"));
      buffer = [];
    }
  }

  return statements;
}

function convertDump(source) {
  const statements = buildStatements(source);
  const output = [
    "-- Arquivo gerado automaticamente a partir de sql/PAPv5.sql",
    "SET standard_conforming_strings = off;",
  ];

  for (const statement of statements) {
    const trimmed = statement.trim();

    if (/^CREATE TABLE /i.test(trimmed)) {
      output.push(transformCreateTable(trimmed));
      continue;
    }

    if (/^ALTER TABLE /i.test(trimmed)) {
      const transformed = transformAlterTable(trimmed);
      if (transformed) output.push(transformed);
      continue;
    }

    if (/^CREATE (PROCEDURE|TRIGGER)/i.test(trimmed)) {
      continue;
    }

    const transformed = transformMiscStatement(trimmed);
    if (transformed) {
      output.push(transformed);
    }
  }

  return output.filter(Boolean).join("\n\n") + "\n";
}

if (!fs.existsSync(inputPath)) {
  console.error(`Arquivo não encontrado: ${inputPath}`);
  process.exit(1);
}

const source = fs.readFileSync(inputPath, "utf8");
const converted = convertDump(source);
fs.writeFileSync(outputPath, converted, "utf8");

console.log(`SQL PostgreSQL gerado em ${path.relative(projectRoot, outputPath)}`);
