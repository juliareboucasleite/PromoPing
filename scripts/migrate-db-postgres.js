function quoteIdentifier(identifier) {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(identifier)) {
    throw new Error(`Identificador inválido: ${identifier}`);
  }
  return `"${identifier.toLowerCase()}"`;
}

async function addColumnIfNotExists(table, column, definition) {
  const [rows] = await pool.query(
    `SELECT COUNT(*)::int AS count
       FROM information_schema.columns
      WHERE table_schema = current_schema()
        AND LOWER(table_name) = LOWER(?)
        AND LOWER(column_name) = LOWER(?)`,
    [table, column]
  );

  if (rows[0].count === 0) {
    await pool.query(
      `ALTER TABLE ${quoteIdentifier(table)} ADD COLUMN ${quoteIdentifier(column)} ${definition}`
    );
    console.log(` Coluna ${column} adicionada à tabela ${table}`);
  }
}

async function columnExists(table, column) {
  const [rows] = await pool.query(
    `SELECT COUNT(*)::int AS count
       FROM information_schema.columns
      WHERE table_schema = current_schema()
        AND LOWER(table_name) = LOWER(?)
        AND LOWER(column_name) = LOWER(?)`,
    [table, column]
  );
  return Number(rows[0].count) > 0;
}

async function dropColumnIfExists(table, column) {
  if (await columnExists(table, column)) {
    await pool.query(
      `ALTER TABLE ${quoteIdentifier(table)} DROP COLUMN ${quoteIdentifier(column)}`
    );
    console.log(` Coluna ${column} removida da tabela ${table}`);
  }
}

