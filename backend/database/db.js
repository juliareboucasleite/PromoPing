import pg from "pg";
import dotenv from "dotenv";
import path from "path";
import { fileURLToPath } from "url";
import { queryWithTableRecovery } from "./tableManager.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: path.join(__dirname, "..", "..", ".env") });

const { Pool, types } = pg;

// Numeric (DECIMAL/NUMERIC) por padrão volta como string em pg.
// O resto do código trata preços como número, então convertemos.
types.setTypeParser(1700, (val) => (val === null ? null : parseFloat(val)));
// BIGINT (8 bytes) também volta como string; convertemos quando cabe em Number.
types.setTypeParser(20, (val) => {
  if (val === null) return null;
  const n = Number(val);
  return Number.isSafeInteger(n) ? n : val;
});

const rawPool = new Pool({
  host: process.env.DB_HOST || "localhost",
  user: process.env.DB_USER || "postgres",
  password: process.env.DB_PASSWORD || "",
  database: process.env.DB_NAME || "papv5",
  port: parseInt(process.env.DB_PORT) || 5432,
  max: 10,
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 5000,
});

rawPool.on("error", (err) => {
  console.error("[DB] Erro inesperado no pool PG:", err.message);
});

// Converte placeholders `?` (mysql2) → `$1, $2, …` (pg).
// Respeita strings entre aspas para não trocar `?` literais dentro de texto.
function convertPlaceholders(sql) {
  if (typeof sql !== "string" || sql.indexOf("?") === -1) return sql;
  let out = "";
  let i = 0;
  let n = 0;
  let inSingle = false;
  let inDouble = false;
  while (i < sql.length) {
    const ch = sql[i];
    if (!inDouble && ch === "'") {
      inSingle = !inSingle;
      out += ch;
    } else if (!inSingle && ch === '"') {
      inDouble = !inDouble;
      out += ch;
    } else if (!inSingle && !inDouble && ch === "?") {
      n += 1;
      out += "$" + n;
    } else {
      out += ch;
    }
    i += 1;
  }
  return out;
}

// No schema atual deste projeto, campos como Ativo/Used/IsActive são INTEGER (1/0).
// Não convertemos `= 1` para `= TRUE` automaticamente — só quebraria queries
// contra colunas integer. Se um dia o schema migrar para BOOLEAN, este é o lugar.

function normalizeMysqlSqlForPg(sql) {
  if (typeof sql !== "string") return sql;

  return sql
    .replace(/`/g, '"')
    .replace(/\bDATABASE\(\)/gi, "current_schema()")
    .replace(/\bCURDATE\(\)/gi, "CURRENT_DATE")
    // Não substituir NOW() — é válido em PG e equivalente; substituir só causa ruído nas regras.
    .replace(/\bint\(\d+\)\s+unsigned/gi, "INTEGER")
    .replace(/\bint\(\d+\)/gi, "INTEGER")
    .replace(/\btinyint\(1\)/gi, "BOOLEAN")
    .replace(/\bdatetime\b/gi, "TIMESTAMP")
    .replace(/\benum\((?:[^)(]+|\([^)(]*\))*\)/gi, "VARCHAR(100)")
    .replace(/\s+ON UPDATE CURRENT_TIMESTAMP/gi, "")
    // Inline `COMMENT 'texto'` em colunas é MySQL-only. PG só aceita COMMENT ON COLUMN à parte.
    .replace(/\s+COMMENT\s+'(?:[^']|'')*'/gi, "")
    .replace(/\bAUTO_INCREMENT\b/gi, "GENERATED BY DEFAULT AS IDENTITY")
    .replace(/\)\s*ENGINE=[\s\S]*?(?=\s*(?:;|$))/gi, ")")
    .replace(/\s+DEFAULT CHARSET=\w+/gi, "")
    .replace(/\s+CHARSET=\w+/gi, "")
    .replace(/\s+COLLATE=\w+/gi, "")
    // Inline `COLLATE utf8/utf8mb4/latin1/...` (MySQL-only collations).
    // Em PG estas colunas comparam-se sem COLLATE — basta remover o clause.
    .replace(/\s+COLLATE\s+(?:utf8mb4|utf8|latin1|ascii|binary)\w*/gi, "")
    .replace(/,\s*INDEX\s+[A-Za-z0-9_]+\s*\([^)]+\)/gi, "")
    .replace(/,\s*KEY\s+[A-Za-z0-9_]+\s*\([^)]+\)/gi, "")
    .replace(/,\s*UNIQUE KEY\s+[A-Za-z0-9_]+\s*\(([^)]+)\)/gi, ", UNIQUE ($1)");
  // Removido: regex `SET T.col` → `SET col`. Era destrutivo em UPDATEs com alias.
}

function ensureInsertReturning(sql) {
  if (typeof sql !== "string") return sql;
  const trimmed = sql.trim();
  if (!/^insert\b/i.test(trimmed) || /\breturning\b/i.test(trimmed)) {
    return sql;
  }
  return `${trimmed.replace(/;+\s*$/, "")} RETURNING *`;
}

function prepareCompatSql(sql) {
  return ensureInsertReturning(normalizeMysqlSqlForPg(convertPlaceholders(sql)));
}

function extractInsertId(rows) {
  if (!Array.isArray(rows) || rows.length === 0 || !rows[0]) return 0;

  const firstRow = rows[0];
  for (const key of ["id", "Id", "ID"]) {
    if (Object.prototype.hasOwnProperty.call(firstRow, key)) {
      return firstRow[key];
    }
  }

  for (const [key, value] of Object.entries(firstRow)) {
    if (/id$/i.test(key) && (typeof value === "number" || typeof value === "string")) {
      return value;
    }
  }

  return 0;
}

// PG dobra identificadores não-quotados para minúsculas, por isso colunas como
// `ReferenciaID` ou `Email` chegam como `referenciaid` / `email`. O código existente
// (centenas de sítios) escrito para mysql2 acede aos campos com a capitalização
// declarada. Envolvemos cada linha num Proxy com lookup case-insensitive para
// preservar essa API sem tocar nas queries.
function caseInsensitiveRow(row) {
  if (!row || typeof row !== "object") return row;
  const lowerMap = Object.create(null);
  for (const key of Object.keys(row)) {
    lowerMap[key.toLowerCase()] = key;
  }
  return new Proxy(row, {
    get(target, prop, receiver) {
      if (typeof prop === "string" && !Object.prototype.hasOwnProperty.call(target, prop)) {
        const real = lowerMap[prop.toLowerCase()];
        if (real !== undefined) return target[real];
      }
      return Reflect.get(target, prop, receiver);
    },
    has(target, prop) {
      if (prop in target) return true;
      if (typeof prop === "string") {
        return lowerMap[prop.toLowerCase()] !== undefined;
      }
      return false;
    },
  });
}

function wrapRows(rows) {
  if (!Array.isArray(rows)) return rows;
  return rows.map(caseInsensitiveRow);
}

function formatCompatResult(result) {
  const command = (result?.command || "").toUpperCase();
  const rows = wrapRows(result?.rows ?? []);

  if (command === "SELECT") {
    return [rows, result.fields];
  }

  return [{
    affectedRows: result?.rowCount ?? 0,
    changedRows: command === "UPDATE" ? (result?.rowCount ?? 0) : 0,
    insertId: command === "INSERT" ? extractInsertId(result?.rows) : 0,
    rowCount: result?.rowCount ?? 0,
    command,
    rows,
  }, result?.fields];
}

// Wrapper que devolve `[rows, fields]` (formato mysql2) para compatibilidade
// com todo o código existente que faz `const [rows] = await pool.query(...)`.
async function compatQuery(sql, params) {
  const text = prepareCompatSql(sql);
  const result = await rawPool.query(text, params || []);
  return formatCompatResult(result);
}

// Versão pg-nativa, caso algum chamador queira `result.rowCount` etc.
async function rawQuery(sql, params) {
  const text = normalizeMysqlSqlForPg(convertPlaceholders(sql));
  return await rawPool.query(text, params || []);
}

// Cria um shim de pool compatível com a API antiga (.query, .execute, .getConnection).
const pool = {
  // Recovery automático de tabelas (envolve compatQuery via tableManager).
  async query(sql, params) {
    return await queryWithTableRecovery(sql, params);
  },
  // mysql2 também tem .execute — mesma interface.
  async execute(sql, params) {
    return await queryWithTableRecovery(sql, params);
  },
  // Conexão dedicada (transações, etc.) — wrapper sobre pg.PoolClient.
  async getConnection() {
    const client = await rawPool.connect();
    return {
      async query(sql, params) {
        const text = prepareCompatSql(sql);
        const result = await client.query(text, params || []);
        return formatCompatResult(result);
      },
      async execute(sql, params) {
        const text = prepareCompatSql(sql);
        const result = await client.query(text, params || []);
        return formatCompatResult(result);
      },
      async beginTransaction() {
        await client.query("BEGIN");
      },
      async commit() {
        await client.query("COMMIT");
      },
      async rollback() {
        await client.query("ROLLBACK");
      },
      release() {
        client.release();
      },
    };
  },
  async end() {
    await rawPool.end();
  },
  // Acesso direto ao pool pg para casos avançados.
  _raw: rawPool,
};

// Query original (sem recovery) usada pelo tableManager para evitar recursão.
pool._originalQuery = compatQuery;
pool._rawQuery = rawQuery;
pool._convertPlaceholders = convertPlaceholders;
pool._normalizeMysqlSqlForPg = normalizeMysqlSqlForPg;
pool._prepareCompatSql = prepareCompatSql;

// Teste de conexão inicial.
rawPool
  .connect()
  .then((client) => client.release())
  .catch((error) => {
    console.error(" Erro ao conectar à base de dados PostgreSQL:", error.message);
    process.exit(1);
  });

export { pool };
